#!/usr/bin/env python3
"""Stage a Kaggle GPU kernel for ``train_v6.py`` (local files only; nothing is uploaded).

Produces ``<out>/kernel-metadata.json`` and ``<out>/run_training.py``. The script finds the attached code
dataset (``train_v6.py`` + modules + ``manifest_v6.csv``), the exported-PNG datasets (folders ``images`` inside
datasets whose name contains ``netrai-train-768``) and the legacy initial weights, installs the pinned timm,
and runs ``train_v6.py`` with the given arguments. ``LEGACY`` as ``--init`` resolves to the legacy state dict.

Uploading (``kaggle datasets create`` / ``kaggle kernels push``) is a separate, explicit step that needs approval.
"""
from __future__ import annotations

import argparse
import json
import shlex
from pathlib import Path

TEMPLATE = '''# Generated by make_kaggle_kernel.py -- NetrAI {title}
import glob, os, shutil, subprocess, sys

code_main = glob.glob('/kaggle/input/**/train_v6.py', recursive=True)
assert code_main, 'attach the code dataset that contains train_v6.py'
code = os.path.dirname(code_main[0])
work = '/kaggle/working/code'
shutil.copytree(code, work, dirs_exist_ok=True)
roots = sorted(d for d in glob.glob('/kaggle/input/**/images', recursive=True) if 'netrai-train-768' in d)
assert roots, 'attach the netrai-train-768 export datasets'
legacy = glob.glob('/kaggle/input/**/legacy_init_state.pt', recursive=True)
subprocess.run([sys.executable, '-m', 'pip', 'install', '-q', 'timm==1.0.29'], check=True)
args = {args!r}
args = [(legacy[0] if a == 'LEGACY' else a) for a in args]
cmd = [sys.executable, 'train_v6.py', '--manifest', os.path.join(work, 'manifest_v6.csv'), '--roots', *roots,
       '--output', '/kaggle/working/run', *args]
print(' '.join(cmd), flush=True)
subprocess.run(cmd, check=True, cwd=work)
'''


LESION_TEMPLATE = '''# Generated by make_kaggle_kernel.py -- NetrAI {title}
import glob, os, shutil, subprocess, sys

code_main = glob.glob('/kaggle/input/**/train_lesion_seg.py', recursive=True)
assert code_main, 'attach the lesion code dataset that contains train_lesion_seg.py'
work = '/kaggle/working/code'
shutil.copytree(os.path.dirname(code_main[0]), work, dirs_exist_ok=True)
manifests = [m for m in glob.glob('/kaggle/input/**/manifest.csv', recursive=True) if 'netrai-lesion' in m]
assert manifests, 'attach the exported lesion dataset (netrai-lesion-*)'
dataset = os.path.dirname(manifests[0])
subprocess.run([sys.executable, '-m', 'pip', 'install', '-q', 'timm==1.0.29'], check=True)
cmd = [sys.executable, 'train_lesion_seg.py', '--dataset', dataset, '--output', '/kaggle/working/run', *{args!r}]
print(' '.join(cmd), flush=True)
subprocess.run(cmd, check=True, cwd=work)
'''


def build_lesion_kernel(out: Path, kernel_id: str, title: str, dataset_sources: list[str], train_args: list[str],
                        username: str = 'abhikrao') -> dict:
    """Stage a kernel running ``train_lesion_seg.py`` (same conventions as ``build_kernel``)."""
    out = Path(out)
    if (out / 'kernel-metadata.json').exists():
        raise FileExistsError(f'{out} already staged; kernels are immutable')
    if '/' in kernel_id or ' ' in kernel_id:
        raise ValueError('kernel_id must be a bare slug')
    for forbidden in ('--dataset', '--output'):
        if forbidden in train_args:
            raise ValueError(f'{forbidden} is set by the template')
    out.mkdir(parents=True, exist_ok=True)
    metadata = {'id': f'{username}/{kernel_id}', 'title': title, 'code_file': 'run_training.py', 'language': 'python',
                'kernel_type': 'script', 'is_private': True, 'enable_gpu': True, 'enable_internet': True,
                'dataset_sources': dataset_sources, 'competition_sources': [], 'kernel_sources': []}
    (out / 'kernel-metadata.json').write_text(json.dumps(metadata, indent=2) + '\n', encoding='utf-8')
    (out / 'run_training.py').write_text(LESION_TEMPLATE.format(title=title, args=list(train_args)), encoding='utf-8')
    return metadata


def build_kernel(out: Path, kernel_id: str, title: str, dataset_sources: list[str], train_args: list[str],
                 username: str = 'abhikrao') -> dict:
    out = Path(out)
    if (out / 'kernel-metadata.json').exists():
        raise FileExistsError(f'{out} already staged; kernels are immutable')
    if '/' in kernel_id or ' ' in kernel_id:
        raise ValueError('kernel_id must be a bare slug')
    for forbidden in ('--manifest', '--roots', '--output'):
        if forbidden in train_args:
            raise ValueError(f'{forbidden} is set by the template')
    out.mkdir(parents=True, exist_ok=True)
    metadata = {'id': f'{username}/{kernel_id}', 'title': title, 'code_file': 'run_training.py', 'language': 'python',
                'kernel_type': 'script', 'is_private': True, 'enable_gpu': True, 'enable_internet': True,
                'dataset_sources': dataset_sources, 'competition_sources': [], 'kernel_sources': []}
    (out / 'kernel-metadata.json').write_text(json.dumps(metadata, indent=2) + '\n', encoding='utf-8')
    (out / 'run_training.py').write_text(TEMPLATE.format(title=title, args=list(train_args)), encoding='utf-8')
    return metadata


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--out', type=Path, required=True)
    parser.add_argument('--id', required=True)
    parser.add_argument('--title', required=True)
    parser.add_argument('--datasets', nargs='+', required=True, help='e.g. abhikrao/netrai-train-768 ...')
    parser.add_argument('--train-args', default='', help='quoted trainer arguments (without the template-owned paths)')
    parser.add_argument('--lesion', action='store_true', help='stage train_lesion_seg.py instead of train_v6.py')
    args = parser.parse_args()
    builder = build_lesion_kernel if args.lesion else build_kernel
    metadata = builder(args.out, args.id, args.title, args.datasets, shlex.split(args.train_args))
    print(json.dumps(metadata, indent=2))


if __name__ == '__main__':
    main()
