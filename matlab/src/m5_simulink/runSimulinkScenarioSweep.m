function results = runSimulinkScenarioSweep(outputDir, totalPatients)
%RUNSIMULINKSCENARIOSWEEP Execute the declared eighteen endpoint-v3 scenarios.
% The calendar is 250 x 8 working-hour-equivalent seconds, not real shift
% availability. Existing model or result evidence is never replaced or healed.
    arguments
        outputDir (1,1) string = ""
        totalPatients (1,1) double {mustBeInteger,mustBePositive} = 100000
    end
    m5Dir = fileparts(mfilename('fullpath'));
    matlabDir = fileparts(fileparts(m5Dir));
    if strlength(outputDir) == 0
        outputDir = fullfile(matlabDir, 'results', 'm5_scenario_sweep_' + ...
            string(datetime('now', 'Format', 'yyyyMMdd_HHmmss')));
    end
    if isfolder(outputDir) || isfile(outputDir)
        error('NetrAI:M5:OutputExists', 'The scenario sweep requires a fresh output directory.');
    end
    outputParent = fileparts(outputDir);
    if strlength(string(outputParent)) == 0, outputParent = string(pwd); end
    if ~isfolder(outputParent), mkdir(outputParent); end
    stagingDir = fullfile(outputParent, ".netrai-staging-m5-" + ...
        string(char(java.util.UUID.randomUUID())));
    mkdir(stagingDir);
    rows = cell(0, 1);
    details = cell(0, 1);
    startedAt = string(datetime('now', 'Format', 'yyyy-MM-dd''T''HH:mm:ss'));
    modelPath = fullfile(matlabDir, 'models', 'NetrAI_Telemedicine_Model.slx');
    try
        if ~isfile(modelPath)
            setupSimulinkModel(modelPath);
        end
        if ~isfile(modelPath + ".manifest.json")
            error('NetrAI:M5:MissingWorkflowManifest', ...
                'The saved model requires its endpoint-v3 manifest; legacy models are not repaired automatically.');
        end
        % Preserve the exact artifact bytes used for this sweep. The scenario
        % wrapper verifies source, model and embedded provenance before and
        % after each run. Changes to active files cannot silently change a run.
        lockedModel = fullfile(stagingDir, 'NetrAI_Telemedicine_Model.slx');
        copyfile(modelPath, lockedModel);
        copyfile(modelPath + ".manifest.json", lockedModel + ".manifest.json");
        sourceIdentity = telemedicineSourceIdentity();
        copySourceSnapshot(stagingDir, sourceIdentity, m5Dir);
        modelDigest = fileSHA256(lockedModel);
        defaultParams = defaultTelemedicineParameters();
        horizon = 250 * 8 * 3600;
        scenarios = combinations([0.25 1.0 5.0], [1 2], [0.05 0.10 0.20]);
        scenarios.Properties.VariableNames = { ...
            'bandwidth_mbps', 'clinicians', 'quality_reject_rate'};
        for index = 1:height(scenarios)
            scenario = scenarios(index, :);
            overrides = struct('totalPatients', totalPatients, ...
                'workingDays', 250, 'operatingHoursPerDay', 8, ...
                'simulationDuration', horizon, 'interarrivalTime', horizon / totalPatients, ...
                'queueCapacity', totalPatients + 2, ...
                'imagesPerPatient', 2, 'imageSizeMB', 3.5, ...
                'bandwidthMbps', scenario.bandwidth_mbps, ...
                'uploadTime', 2 * 3.5 * 8 / scenario.bandwidth_mbps, ...
                'clinicianCount', scenario.clinicians, ...
                'qualityRejectRate', scenario.quality_reject_rate, ...
                'retryQualityRejectRate', scenario.quality_reject_rate, ...
                'maxRecaptureRetries', 2, 'recaptureAbandonRate', 0, ...
                'qualityRandomSeed', 4200 + index, 'triageRandomSeed', 5200 + index, ...
                'traceEnabled', false);
            detail = runTelemedicineScenario(lockedModel, overrides);
            if string(detail.model_sha256) ~= string(modelDigest) || ...
                    string(detail.source_identity.source_sha256) ~= string(sourceIdentity.source_sha256)
                error('NetrAI:M5:ArtifactChanged', 'Sweep artifacts changed between scenarios.');
            end
            detail.scenario_id = index;
            row = summaryRow(detail, index, totalPatients, scenario);
            rows{end+1, 1} = row;
            details{end+1, 1} = detail;
            % Interrupted/failed evidence remains in this private staging
            % directory. It is never published as a complete eighteen-row run.
            writeJson(fullfile(stagingDir, sprintf('scenario_%02d.json', index)), detail);
            writetable(struct2table(vertcat(rows{:})), fullfile(stagingDir, ...
                'simulink_scenario_sweep.partial.csv'));
            fprintf(['M5 v3 %02d/%02d: %.2f Mbps, %d reviewer(s), reject %.0f%% ' ...
                '-> %d generated, %d completed, %d in-system, %d exhausted, %d abandoned\n'], ...
                index, height(scenarios), row.bandwidth_mbps, row.clinicians, ...
                100*row.quality_reject_rate, row.generated, row.completed, ...
                row.in_system, row.quality_exhausted, row.abandoned);
        end
        % A final whole-sweep content recheck closes the gap between the final
        % scenario and result publication. Default/source changes invalidate it.
        finalIdentity = telemedicineSourceIdentity();
        if string(finalIdentity.source_sha256) ~= string(sourceIdentity.source_sha256) || ...
                string(fileSHA256(lockedModel)) ~= string(modelDigest) || ...
                string(fileSHA256(modelPath)) ~= string(modelDigest) || ...
                string(fileSHA256(modelPath + ".manifest.json")) ~= ...
                    string(fileSHA256(lockedModel + ".manifest.json"))
            error('NetrAI:M5:ArtifactChanged', 'Workflow artifacts changed before sweep publication.');
        end
        results = struct2table(vertcat(rows{:}));
        writetable(results, fullfile(stagingDir, 'simulink_scenario_sweep.csv'));
        payload = struct('schema_version', 3, 'endpoint_version', 3, ...
            'model', 'NetrAI_Telemedicine_Model.slx', 'model_sha256', modelDigest, ...
            'source_identity', sourceIdentity, 'started_at', char(startedAt), ...
            'scope', 'Configured district screening workload in working-hour-equivalent seconds.', ...
            'scenario_count', height(results), 'complete', true, ...
            'calendar_assumption', struct('working_days_equivalent', 250, ...
                'operating_hours_per_day_equivalent', 8, 'horizon_seconds', horizon, ...
                'closed_hours_or_shifts_modeled', false), ...
            'payload_assumption', struct('images_per_patient', 2, ...
                'image_size_mb', 3.5, 'upload_megabits_per_patient', 56), ...
            'retry_assumption', struct('max_recapture_retries', 2, ...
                'return_delay_seconds', defaultParams.recaptureTime, ...
                'retry_rejection_equals_initial_rejection', true, ...
                'dropout_probability_per_permitted_retry', 0, ...
                'dropout_assessed_before_return_delay', true), ...
            'counter_definitions', counterDefinitions(), ...
            'results', table2struct(results), 'limitations', {{ ...
                'Quality rejection, retry rejection, dropout and routing are unfitted scenario assumptions.', ...
                'Zero dropout is an explicit scenario assumption, not an observed return rate.', ...
                'Patient outcomes and attempt counters have different denominators.', ...
                'Mean review queue wait covers patients that started review; censored waiting cases remain in-system.', ...
                'No patient wait percentile is reported; no shift calendar or overdue-review escalation is modeled.', ...
                'Endpoint-v2 results remain historical and are not interchangeable with endpoint-v3 outcomes.'}});
        writeJson(fullfile(stagingDir, 'simulink_scenario_sweep.json'), payload);
        if isfolder(outputDir) || isfile(outputDir)
            error('NetrAI:M5:OutputExists', 'The requested result destination appeared during the sweep.');
        end
        [moved, message] = movefile(stagingDir, outputDir);
        if ~moved, error('NetrAI:M5:PublishFailed', '%s', message); end
    catch exception
        failure = struct('schema_version', 3, 'endpoint_version', 3, ...
            'complete', false, 'completed_scenarios', numel(rows), ...
            'error_identifier', exception.identifier, 'error_message', exception.message, ...
            'started_at', char(startedAt), 'staging_directory', char(stagingDir));
        if isfolder(stagingDir)
            writeJson(fullfile(stagingDir, 'FAILED.json'), failure);
        end
        rethrow(exception);
    end
end

function row = summaryRow(detail, index, totalPatients, scenario)
    row = struct('endpoint_version', 3, 'scenario_id', index, ...
        'total_patients_target', totalPatients, ...
        'planned_arrivals_including_start_and_cutoff', totalPatients+1, ...
        'generated', detail.generated, 'bandwidth_mbps', scenario.bandwidth_mbps, ...
        'clinicians', scenario.clinicians, 'quality_reject_rate', scenario.quality_reject_rate, ...
        'retry_quality_reject_rate', detail.parameters.retryQualityRejectRate, ...
        'max_recapture_retries', detail.parameters.maxRecaptureRetries, ...
        'recapture_abandon_rate', detail.parameters.recaptureAbandonRate, ...
        'auto_cleared', detail.auto_cleared, 'reviewed', detail.reviewed, ...
        'completed', detail.completed, 'abandoned', detail.abandoned, ...
        'quality_exhausted', detail.quality_exhausted, 'in_system', detail.in_system, ...
        'unfinished_at_stop', detail.unfinished, ...
        'conservation_residual', detail.conservation_residual, ...
        'acquisition_attempts_started', detail.acquisition_attempts_started, ...
        'quality_checks_completed', detail.quality_checks_completed, ...
        'recapture_requests', detail.recap_requests, ...
        'recapture_returns', detail.recapture_returns, ...
        'recapture_pending', detail.recapture_pending, ...
        'acquisition_attempts_per_generated_patient', detail.acquisition_attempts_per_generated_patient, ...
        'completion_rate', detail.completion_rate, 'unfinished_rate', detail.unfinished_rate, ...
        'abandonment_rate', detail.abandonment_rate, ...
        'quality_exhaustion_rate', detail.quality_exhaustion_rate, ...
        'in_system_rate', detail.in_system_rate, ...
        'review_rate_among_completed', detail.review_rate_among_completed, ...
        'clinician_utilization_at_stop', detail.clinician_utilization, ...
        'last_departure_clinician_utilization_statistic', detail.last_departure_clinician_utilization_statistic, ...
        'mean_queue_wait_for_review_starts_seconds', detail.review_running_average_wait_seconds, ...
        'mean_completed_review_service_residence_seconds', detail.review_service_running_average_time_seconds, ...
        'max_acquisition_queue', detail.max_acquisition_queue, ...
        'max_recapture_queue', detail.max_recapture_queue, ...
        'max_upload_queue', detail.max_upload_queue, 'max_ai_queue', detail.max_ai_queue, ...
        'max_review_queue', detail.max_review_queue, ...
        'throughput_patients_per_working_hour_equivalent', detail.completed/(250*8), ...
        'expected_quality_acceptance_probability', detail.expected_quality_acceptance_probability, ...
        'required_review_clinicians_at_80pct_utilization', detail.required_review_clinicians_at_80pct_utilization, ...
        'runtime_seconds', detail.runtime_seconds);
end

function definitions = counterDefinitions()
    definitions = struct( ...
        'generated', 'Observed generator departures plus any generator-pending patient.', ...
        'completed', 'Disjoint original patients auto-cleared or reviewed.', ...
        'unfinished', 'Abandoned plus quality-exhausted plus physically in-system patients.', ...
        'in_system', 'Independent sum of queue/server occupancy plus generator pending.', ...
        'recapture_requests_returns_pending', 'Attempt-level counts; the same patient may appear more than once.', ...
        'acquisition_attempts', 'Attempt-level count, bounded by generated*(max_retries+1).');
end

function copySourceSnapshot(outputDir, identity, m5Dir)
    for index = 1:numel(identity.source_files)
        entry = identity.source_files(index);
        label = string(entry.path);
        [~, fileName, extension] = fileparts(label);
        if startsWith(label, "src/m5_simulink/")
            sourcePath = fullfile(m5Dir, fileName + extension);
        else
            sourcePath = string(which(fileName));
        end
        destination = fullfile(outputDir, 'source_snapshot', label);
        parent = fileparts(destination);
        if ~isfolder(parent), mkdir(parent); end
        copyfile(sourcePath, destination);
        if string(fileSHA256(destination)) ~= string(entry.sha256)
            error('NetrAI:M5:ArtifactChanged', 'A workflow source changed during snapshot.');
        end
    end
end

function writeJson(path, payload)
    fileId = fopen(path, 'w');
    if fileId < 0, error('NetrAI:M5:OutputWrite', 'Could not write %s.', path); end
    cleaner = onCleanup(@() fclose(fileId));
    fprintf(fileId, '%s\n', jsonencode(payload, 'PrettyPrint', true));
    clear cleaner;
end
