function modelPath = setupSimulinkModel(outputPath)
%SETUPSIMULINKMODEL Build the content-bound endpoint-v3 district workflow.
% One original patient entity is reused for bounded acquisition retries.

    arguments
        outputPath (1,1) string = ""
    end
    m5Dir = fileparts(mfilename('fullpath'));
    matlabDir = fileparts(fileparts(m5Dir));
    if strlength(outputPath) == 0
        outputPath = fullfile(matlabDir, 'models', ...
            'NetrAI_Telemedicine_Model.slx');
    end
    modelName = "NetrAI_Telemedicine_Model";
    [outputDir, fileName, extension] = fileparts(outputPath);
    if string(fileName) ~= modelName || string(extension) ~= ".slx"
        error('NetrAI:M5:ModelName', ...
            'The workflow model must use NetrAI_Telemedicine_Model.slx.');
    end
    if isfile(outputPath) || isfile(outputPath + ".manifest.json")
        error('NetrAI:M5:OutputExists', ...
            'Use a fresh workflow model path; existing files are preserved.');
    end
    if bdIsLoaded(modelName)
        error('NetrAI:M5:ModelAlreadyLoaded', ...
            'Close the existing workflow model before building a fresh saved model.');
    end
    if ~isfolder(outputDir), mkdir(outputDir); end
    load_system('simulink');
    load_system('sldelib');
    new_system(modelName, 'Model');
    cleaner = onCleanup(@() closeWorkflowModel(modelName));
    params = defaultTelemedicineParameters();
    workspace = get_param(modelName, 'ModelWorkspace');
    names = fieldnames(params);
    for index = 1:numel(names)
        workspace.assignin(names{index}, params.(names{index}));
    end
    set_param(modelName, 'StopTime', 'simulationDuration', ...
        'SolverType', 'Variable-step', 'Solver', 'VariableStepDiscrete', ...
        'SaveTime', 'on', 'ReturnWorkspaceOutputs', 'on', ...
        'Description', ['Endpoint-v3 district workflow engineering model. ' ...
        'One patient entity, bounded quality retries, dropout, exhaustion ' ...
        'and conserved patient outcomes. The annual horizon is 250 x 8 ' ...
        'working-hour-equivalent seconds; closed hours and shifts are not modeled.']);

    add_block('sldelib/Entity Generator', modelName + "/Patient Arrivals", ...
        'Position', [30 230 145 290], ...
        'GenerationMethod', 'Time-based', 'TimeSource', 'Dialog', ...
        'Period', 'interarrivalTime', 'GenerateEntityAtSimulationStart', 'on', ...
        'EntityType', 'Structured', ...
        'AttributeName', 'PatientId|Attempt|Route', ...
        'AttributeInitialValue', '0|0|1', ...
        'GenerateAction', generationAction(), ...
        'NumberEntitiesDeparted', 'on', 'PendingEntityInBlock', 'on');
    add_block('sldelib/Entity Input Switch', modelName + "/Acquisition Merge", ...
        'Position', [200 205 270 320], 'NumberInputPorts', '2', ...
        'ActivePortSelection', 'All', 'SwitchingCriterion', 'Round robin');
    addQueue(modelName, "Acquisition Queue", [325 230 420 290]);
    addServer(modelName, "Image Acquisition", [475 230 590 290], ...
        'acquisitionTime', '1', qualityAction());
    set_param(modelName + "/Image Acquisition", 'EntryAction', ...
        joinActions('entity.Attempt = entity.Attempt + 1;', ...
        traceAction(2)));
    add_block('sldelib/Entity Output Switch', modelName + "/Quality Gate", ...
        'Position', [645 185 735 335], 'NumberOutputPorts', '4', ...
        'SwitchingCriterion', 'From attribute', 'SwitchAttributeName', 'Route');

    addQueue(modelName, "Recapture Queue", [790 65 885 125]);
    % The delay is a return interval for each patient, not a single serial
    % technician. Repeat acquisition uses the same shared acquisition server.
    addServer(modelName, "Recapture Return Delay", [940 65 1055 125], ...
        'recaptureTime', 'queueCapacity', '');
    set_param(modelName + "/Recapture Return Delay", ...
        'ExitAction', traceAction(4));
    addTerminator(modelName, "Abandoned", [790 370 890 420], 7);
    addTerminator(modelName, "Quality Exhausted", [790 470 920 520], 8);

    addQueue(modelName, "Upload Queue", [790 205 885 265]);
    addServer(modelName, "Bandwidth Upload", [940 205 1055 265], ...
        'uploadTime', '1', '');
    addQueue(modelName, "AI Queue", [1110 205 1205 265]);
    addServer(modelName, "AI Inference", [1260 205 1375 265], ...
        'aiInferenceTime', '1', triageAction());
    add_block('sldelib/Entity Output Switch', modelName + "/Safety Triage", ...
        'Position', [1430 165 1520 295], 'NumberOutputPorts', '3', ...
        'SwitchingCriterion', 'From attribute', 'SwitchAttributeName', 'Route');
    addTerminator(modelName, "Auto Clear", [1575 95 1685 145], 5);
    addQueue(modelName, "Referral Queue", [1575 205 1670 265]);
    addQueue(modelName, "Uncertain Queue", [1575 330 1670 390]);
    add_block('sldelib/Entity Input Switch', modelName + "/Review Merge", ...
        'Position', [1725 225 1800 370], 'NumberInputPorts', '2', ...
        'ActivePortSelection', 'All', 'SwitchingCriterion', 'Round robin');
    addQueue(modelName, "Review Queue", [1855 270 1950 330]);
    set_param(modelName + "/Review Queue", 'AverageWait', 'on');
    addServer(modelName, "Clinician Review", [2005 270 2120 330], ...
        'reviewTimePerPatient', 'clinicianCount', '');
    set_param(modelName + "/Clinician Review", ...
        'AverageWait', 'on', 'Utilization', 'on');
    addTerminator(modelName, "Reviewed", [2175 275 2275 325], 6);

    connectEntity(modelName, "Patient Arrivals", 1, "Acquisition Merge", 1);
    connectEntity(modelName, "Recapture Return Delay", 1, "Acquisition Merge", 2);
    connectEntity(modelName, "Acquisition Merge", 1, "Acquisition Queue", 1);
    connectEntity(modelName, "Acquisition Queue", 1, "Image Acquisition", 1);
    connectEntity(modelName, "Image Acquisition", 1, "Quality Gate", 1);
    connectEntity(modelName, "Quality Gate", 1, "Upload Queue", 1);
    connectEntity(modelName, "Quality Gate", 2, "Recapture Queue", 1);
    connectEntity(modelName, "Quality Gate", 3, "Abandoned", 1);
    connectEntity(modelName, "Quality Gate", 4, "Quality Exhausted", 1);
    connectEntity(modelName, "Recapture Queue", 1, "Recapture Return Delay", 1);
    connectEntity(modelName, "Upload Queue", 1, "Bandwidth Upload", 1);
    connectEntity(modelName, "Bandwidth Upload", 1, "AI Queue", 1);
    connectEntity(modelName, "AI Queue", 1, "AI Inference", 1);
    connectEntity(modelName, "AI Inference", 1, "Safety Triage", 1);
    connectEntity(modelName, "Safety Triage", 1, "Auto Clear", 1);
    connectEntity(modelName, "Safety Triage", 2, "Referral Queue", 1);
    connectEntity(modelName, "Safety Triage", 3, "Uncertain Queue", 1);
    connectEntity(modelName, "Referral Queue", 1, "Review Merge", 1);
    connectEntity(modelName, "Uncertain Queue", 1, "Review Merge", 2);
    connectEntity(modelName, "Review Merge", 1, "Review Queue", 1);
    connectEntity(modelName, "Review Queue", 1, "Clinician Review", 1);
    connectEntity(modelName, "Clinician Review", 1, "Reviewed", 1);

    addStatistic(modelName, "Patient Arrivals", "arrivalsDeparted", 1);
    addStatistic(modelName, "Patient Arrivals", "generatorPending", 2);
    queues = ["Acquisition Queue", "Recapture Queue", "Upload Queue", ...
        "AI Queue", "Referral Queue", "Uncertain Queue", "Review Queue"];
    queueSignals = ["acquisitionQueueN", "recaptureQueueN", "uploadQueueN", ...
        "aiQueueN", "referralQueueN", "uncertainQueueN", "reviewQueueN"];
    for index = 1:numel(queues)
        addStatistic(modelName, queues(index), queueSignals(index), 1);
    end
    servers = ["Image Acquisition", "Recapture Return Delay", ...
        "Bandwidth Upload", "AI Inference", "Clinician Review"];
    serverSignals = ["acquisition", "recapture", "upload", "ai", "review"];
    for index = 1:numel(servers)
        addStatistic(modelName, servers(index), serverSignals(index) + "D", 1);
        addStatistic(modelName, servers(index), serverSignals(index) + "N", 2);
    end
    addStatistic(modelName, "Review Queue", "reviewQueueRunningAverageWait", 2);
    addStatistic(modelName, "Clinician Review", "reviewServiceRunningAverageTime", 3);
    addStatistic(modelName, "Clinician Review", "clinicianUtilization", 4);
    terminals = ["Auto Clear", "Reviewed", "Abandoned", "Quality Exhausted"];
    terminalSignals = ["autoCleared", "reviewed", "abandoned", "qualityExhausted"];
    for index = 1:numel(terminals)
        addStatistic(modelName, terminals(index), terminalSignals(index), 1);
    end
    identity = telemedicineSourceIdentity();
    % Root block diagrams do not expose block UserData in R2026a. Persist
    % workflow provenance in the model workspace, alongside its parameters.
    workspace.assignin('m5EndpointVersion', 3);
    workspace.assignin('m5SourceIdentity', identity);
    set_param(modelName, 'ZoomFactor', 'FitSystem');
    save_system(modelName, outputPath);
    manifest = struct('schema_version', 1, 'endpoint_version', 3, ...
        'model_file', 'NetrAI_Telemedicine_Model.slx', ...
        'model_sha256', char(fileSHA256(outputPath)), ...
        'source_identity', identity, ...
        'default_parameters', params, ...
        'assumption_scope', 'Configured engineering assumptions; not fitted population rates.');
    manifestPath = outputPath + ".manifest.json";
    if isfile(manifestPath)
        error('NetrAI:M5:OutputExists', 'Existing workflow manifests are preserved.');
    end
    manifestFile = fopen(manifestPath, 'w');
    if manifestFile < 0
        error('NetrAI:M5:ManifestWrite', 'Could not write the workflow model manifest.');
    end
    manifestCleaner = onCleanup(@() fclose(manifestFile));
    fprintf(manifestFile, '%s\n', jsonencode(manifest, 'PrettyPrint', true));
    clear manifestCleaner;
    clear cleaner;
    modelPath = outputPath;
end

function action = generationAction()
    action = joinActions( ...
        'persistent patientCounter;', ...
        'if isempty(patientCounter), patientCounter = 0; end', ...
        'patientCounter = patientCounter + 1;', ...
        'entity.PatientId = patientCounter;', ...
        'entity.Attempt = 0;', ...
        'entity.Route = 1;', traceAction(1));
end

function action = qualityAction()
    action = joinActions( ...
        'persistent randomInitialized;', ...
        'if isempty(randomInitialized)', ...
        '    rng(qualityRandomSeed);', ...
        '    randomInitialized = true;', ...
        'end', ...
        'if entity.Attempt == 1', ...
        '    rejectProbability = qualityRejectRate;', ...
        'else', ...
        '    rejectProbability = retryQualityRejectRate;', ...
        'end', ...
        'rejected = rand() < rejectProbability;', ...
        'if ~rejected', ...
        '    entity.Route = 1;', ...
        'elseif entity.Attempt > maxRecaptureRetries', ...
        '    entity.Route = 4;', ...
        'elseif rand() < recaptureAbandonRate', ...
        '    entity.Route = 3;', ...
        'else', ...
        '    entity.Route = 2;', ...
        'end', traceAction(3));
end

function action = triageAction()
    action = joinActions( ...
        'persistent randomInitialized;', ...
        'if isempty(randomInitialized)', ...
        '    rng(triageRandomSeed);', ...
        '    randomInitialized = true;', ...
        'end', ...
        'u = rand();', ...
        'if u < autoClearRate', ...
        '    entity.Route = 1;', ...
        'elseif u < autoClearRate + referRate', ...
        '    entity.Route = 2;', ...
        'else', ...
        '    entity.Route = 3;', ...
        'end');
end

function action = traceAction(eventCode)
    action = joinActions( ...
        'coder.extrinsic(''recordTelemedicineEvent'');', ...
        'if traceEnabled', ...
        sprintf('    recordTelemedicineEvent(%d, entity.PatientId, entity.Attempt, entity.Route);', eventCode), ...
        'end');
end

function action = joinActions(varargin)
    action = char(strjoin(string(varargin), newline));
end

function addQueue(modelName, name, position)
    add_block('sldelib/Entity Queue', modelName + "/" + name, ...
        'Position', position, 'Capacity', 'queueCapacity', ...
        'QueueType', 'FIFO', 'NumberEntitiesInBlock', 'on');
end

function addServer(modelName, name, position, serviceTime, capacity, action)
    add_block('sldelib/Entity Server', modelName + "/" + name, ...
        'Position', position, 'Capacity', capacity, ...
        'ServiceTimeSource', 'Dialog', 'ServiceTimeValue', serviceTime, ...
        'NumberEntitiesDeparted', 'on', 'NumberEntitiesInBlock', 'on');
    if strlength(string(action)) > 0
        set_param(modelName + "/" + name, 'ServiceCompleteAction', action);
    end
end

function addTerminator(modelName, name, position, eventCode)
    add_block('sldelib/Entity Terminator', modelName + "/" + name, ...
        'Position', position, 'NumberEntitiesArrived', 'on', ...
        'EntryAction', traceAction(eventCode));
end

function addStatistic(modelName, name, variableName, signalIndex)
    source = get_param(modelName + "/" + name, 'PortHandles');
    modes = split(string(get_param(modelName + "/" + name, ...
        'OutputPortMessageModes')), ',');
    if strcmp(get_param(modelName + "/" + name, 'BlockType'), 'EntityTerminator')
        % A terminator has no entity output. R2026a leaves its message-mode
        % property empty even when the numeric arrival statistic is enabled.
        numericPorts = source.Outport;
    else
        numericPorts = source.Outport(modes == "n");
    end
    if numel(numericPorts) < signalIndex
        error('NetrAI:M5:MissingStatisticPort', ...
            '%s is missing statistic port %d.', name, signalIndex);
    end
    sourcePosition = get_param(numericPorts(signalIndex), 'Position');
    add_block('simulink/Sinks/To Workspace', modelName + "/Log " + variableName, ...
        'Position', [sourcePosition + [5 -55], sourcePosition + [115 -35]], ...
        'VariableName', variableName, 'SaveFormat', 'Timeseries');
    sink = get_param(modelName + "/Log " + variableName, 'PortHandles');
    add_line(modelName, numericPorts(signalIndex), sink.Inport(1), ...
        'autorouting', 'on');
end

function connectEntity(modelName, sourceName, sourceIndex, destinationName, destinationIndex)
    source = get_param(modelName + "/" + sourceName, 'PortHandles');
    destination = get_param(modelName + "/" + destinationName, 'PortHandles');
    sourceModes = split(string(get_param(modelName + "/" + sourceName, ...
        'OutputPortMessageModes')), ',');
    sources = source.Outport(sourceModes == "m");
    destinationModes = split(string(get_param(modelName + "/" + destinationName, ...
        'InputPortMessageModes')), ',');
    destinations = destination.Inport(destinationModes == "m");
    add_line(modelName, sources(sourceIndex), destinations(destinationIndex), ...
        'autorouting', 'on');
end

function closeWorkflowModel(modelName)
    if bdIsLoaded(modelName), close_system(modelName, 0); end
end
